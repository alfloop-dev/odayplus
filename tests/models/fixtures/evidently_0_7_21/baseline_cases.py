def case_by_id(case_id: str) -> DriftCase:
    for case in ALL_CASES:
        if case.case_id == case_id:
            return case
    raise KeyError(case_id)


def execute(case: DriftCase) -> Any:
    """Run one case against the live pinned Evidently engine."""

    from modules.learninghub.infrastructure import EvidentlyDriftMonitor

    monitor = EvidentlyDriftMonitor()
    if case.kind == "data_drift":
        return monitor.run(
            reference_rows=list(case.reference_rows),
            current_rows=list(case.current_rows),
            **case.call_kwargs,
        )
    return monitor.run_prediction(
        reference_rows=list(case.reference_rows),
        current_rows=list(case.current_rows),
        **case.call_kwargs,
    )

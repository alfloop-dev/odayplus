#: ``EvidentlyDriftResult.snapshot_id`` falls back to ``f"evidently-{uuid4()}"``.
#: That value is the only non-semantic field in the whole contract, so it is the
#: only thing this baseline is allowed to normalize. See ``normalize_result``.
AUTO_SNAPSHOT_PLACEHOLDER = "<auto-generated-uuid4>"
_AUTO_SNAPSHOT_PATTERN = re.compile(
    r"^evidently-[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$"
)

NORMALIZATION_POLICY = {
    "normalized": [
        "EvidentlyDriftResult.snapshot_id when the caller passed snapshot_id=None; "
        f"the uuid4 form is verified against a regex and replaced by {AUTO_SNAPSHOT_PLACEHOLDER!r}",
    ],
    "never_normalized": [
        "statistic / p-value / distance values",
        "stat-test method names and thresholds",
        "drift_detected, drifted_columns, drift_share, drifted_column_names",
        "category labels and column names",
        "metric ids, metric ordering and report structure",
        "exception types and messages of validation or runtime failures",
        "caller-supplied snapshot ids, model metadata, cohort and policy version",
    ],
}


@dataclass(frozen=True)
class DriftCase:
    """One reproducible call into ``EvidentlyDriftMonitor``."""

    case_id: str
    kind: str
    description: str
    routing_expectation: str
    reference_rows: tuple[Mapping[str, Any], ...]
    current_rows: tuple[Mapping[str, Any], ...]
    call_kwargs: Mapping[str, Any] = field(default_factory=dict)
    profiled_columns: tuple[str, ...] | None = None
    expects_failure: bool = False

    @property
    def expects_auto_snapshot(self) -> bool:
        return self.kind == "data_drift" and self.call_kwargs.get("snapshot_id") is None


def _sha256_rows(rows: Sequence[Mapping[str, Any]]) -> str:
    payload = json.dumps(list(rows), sort_keys=True, default=repr)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def canonical_json(payload: Any) -> str:
    """Stable serialization used for every golden file and every hash."""

    return json.dumps(payload, sort_keys=True, indent=2, ensure_ascii=False) + "\n"


def _cleaned(series: pd.Series) -> pd.Series:
    """Reproduce Evidently's per-column cleaning before stat-test selection.

    ``evidently/legacy/calculations/data_drift.py:138-149`` replaces +/-inf with
    NaN and drops NaN on both frames before ``get_stattest`` is called, so the
    ``N`` that drives the <=1000 / >1000 branch is the *cleaned* reference size,
    not the raw row count.
    """

    return series.replace([np.inf, -np.inf], np.nan).dropna()


def profile_columns(
    reference_rows: Sequence[Mapping[str, Any]],
    current_rows: Sequence[Mapping[str, Any]],
    columns: Sequence[str] | None = None,
) -> dict[str, dict[str, Any]]:
    """Record the dtypes, cleaned N and merged unique count of every column."""

    if not reference_rows or not current_rows:
        return {}
    reference = pd.DataFrame(list(reference_rows))
    current = pd.DataFrame(list(current_rows))
    names = list(columns) if columns is not None else list(reference.columns)
    names = [name for name in names if name in reference.columns and name in current.columns]
    profile: dict[str, dict[str, Any]] = {}
    for name in names:
        reference_clean = _cleaned(reference[name])
        current_clean = _cleaned(current[name])
        profile[name] = {
            "dtype_reference": str(reference[name].dtype),
            "dtype_current": str(current[name].dtype),
            "raw_reference_n": int(reference[name].shape[0]),
            "raw_current_n": int(current[name].shape[0]),
            "cleaned_reference_n": int(reference_clean.shape[0]),
            "cleaned_current_n": int(current_clean.shape[0]),
            "merged_unique": int(pd.concat([reference_clean, current_clean]).nunique()),
        }
    return profile


def input_receipt(case: DriftCase) -> dict[str, Any]:
    columns = case.profiled_columns
    if columns is None and case.kind != "data_drift":
        columns = tuple(case.call_kwargs.get("prediction_columns", ()) or ())
    return {
        "call_kwargs": json.loads(json.dumps(dict(case.call_kwargs), sort_keys=True, default=repr)),
        "kind": case.kind,
        "description": case.description,
        "routing_expectation": case.routing_expectation,
        "expects_failure": case.expects_failure,
        "reference_row_count": len(case.reference_rows),
        "current_row_count": len(case.current_rows),
        "reference_rows_sha256": _sha256_rows(case.reference_rows),
        "current_rows_sha256": _sha256_rows(case.current_rows),
        "columns": profile_columns(case.reference_rows, case.current_rows, columns or None),
    }


def normalize_result(result: Any, *, expects_auto_snapshot: bool) -> dict[str, Any]:
    """Project an ``EvidentlyDriftResult`` onto the golden contract.

    The only value that changes between two identical runs is the auto-generated
    ``snapshot_id``; it is validated as a uuid4-shaped Evidently id and then
    replaced. Every statistic, threshold, flag and label is passed through
    untouched.
    """

    snapshot_id = result.snapshot_id
    if expects_auto_snapshot:
        if not _AUTO_SNAPSHOT_PATTERN.match(snapshot_id):
            raise AssertionError(
                f"expected an auto-generated evidently-<uuid4> snapshot id, got {snapshot_id!r}"
            )
        snapshot_id = AUTO_SNAPSHOT_PLACEHOLDER
    elif _AUTO_SNAPSHOT_PATTERN.match(snapshot_id):
        raise AssertionError(
            "caller supplied a snapshot id but the result carries an auto-generated one"
        )

    contract = result.to_dict()
    contract["snapshot_id"] = snapshot_id
    return {
        "result": {
            "snapshot_id": snapshot_id,
            "drift_detected": result.drift_detected,
            "drifted_columns": result.drifted_columns,
            "drift_share": result.drift_share,
            "engine": result.engine,
            "reference_snapshot_id": result.reference_snapshot_id,
            "current_snapshot_id": result.current_snapshot_id,
            "model_name": result.model_name,
            "model_version": result.model_version,
            "cohort_key": result.cohort_key,
            "prediction_columns": list(result.prediction_columns),
            "prediction_output_types": (
                dict(result.prediction_output_types)
                if result.prediction_output_types is not None
                else None
            ),
            "drifted_column_names": list(result.drifted_column_names),
            "decision_policy_version_id": result.decision_policy_version_id,
        },
        "to_dict": contract,
        "metrics_index": metrics_index(json.loads(result.report_json)),
    }


def metrics_index(payload: Mapping[str, Any]) -> dict[str, Any]:
    """Flatten the report into the per-column facts §6.3 asks to compare."""

    index: dict[str, Any] = {"drifted_columns_count": None, "columns": {}}
    for metric in payload.get("metrics", []):
        config = metric.get("config", {})
        name = str(metric.get("metric_name", ""))
        if name.startswith("DriftedColumnsCount"):
            index["drifted_columns_count"] = {
                "metric_name": name,
                "id": metric.get("id"),
                "drift_share_argument": config.get("drift_share"),
                "count": metric.get("value", {}).get("count"),
                "share": metric.get("value", {}).get("share"),
            }
            continue
        if "ValueDrift" not in name:
            continue
        index["columns"][str(config.get("column"))] = {
            "metric_name": name,
            "id": metric.get("id"),
            "method": config.get("method"),
            "threshold": config.get("threshold"),
            "value": metric.get("value"),
        }
    return index


def normalize_failure(error: BaseException) -> dict[str, Any]:
    return {
        "exception_type": type(error).__name__,
        "exception_module": type(error).__module__,
        "exception_message": str(error),
    }


def utc_now_iso() -> str:
    return datetime.now(tz=UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def is_close(observed: float, expected: float, *, rel_tol: float, abs_tol: float) -> bool:
    if isinstance(observed, bool) or isinstance(expected, bool):
        return observed is expected
    if math.isnan(float(expected)):
        return math.isnan(float(observed))
    return math.isclose(float(observed), float(expected), rel_tol=rel_tol, abs_tol=abs_tol)



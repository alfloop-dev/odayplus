"""Synthetic fixtures for the pinned Evidently 0.7.21 drift-monitoring baseline.

This module is the single source of truth for the baseline inputs. Both the
generator (``generate_baseline.py``) and the regression suite
(``tests/models/test_evidently_monitor_baseline.py``) import it, so a golden
file can never describe inputs that differ from the ones the test replays.

Everything here is synthetic and closed-form: no external data provider is
contacted, no NLP corpus or model is downloaded, and no secret or personal data
is used. The only randomness is ``numpy.random.default_rng(RNG_SEED)``, whose
draws are rounded to ``RNG_DECIMALS`` so the recorded fixtures stay readable and
byte-stable.

Case ``routing_expectation`` values name the branch of the Evidently 0.7.21
selector at ``evidently/legacy/calculations/stattests/registry.py::
_get_default_stattest``. They are documentation of intent only -- the assertions
compare against the method that the pinned runtime actually reported, never
against this string.
"""


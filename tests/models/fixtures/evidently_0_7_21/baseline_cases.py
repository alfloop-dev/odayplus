def _numeric_rows(values: Sequence[Any], column: str = "demand") -> tuple[dict[str, Any], ...]:
    return tuple({column: value} for value in values)


def _categorical_rows(values: Sequence[Any], column: str = "region") -> tuple[dict[str, Any], ...]:
    return tuple({column: value} for value in values)


def _text_sentence(vocabulary: Sequence[str], index: int) -> str:
    words = [vocabulary[(index * (offset + 1)) % len(vocabulary)] for offset in range(10)]
    return " ".join(words) + f" unit {index}"


def _text_rows(vocabulary: Sequence[str], count: int, column: str = "note") -> tuple[dict[str, Any], ...]:
    return tuple({column: _text_sentence(vocabulary, index)} for index in range(count))


def _normal_values(count: int, *, loc: float, scale: float, stream: int) -> tuple[float, ...]:
    """Draw from a fixed-seed PCG64 stream and round for a byte-stable fixture."""

    generator = np.random.default_rng([RNG_SEED, stream])
    draws = generator.normal(loc=loc, scale=scale, size=count)
    return tuple(round(float(value), RNG_DECIMALS) for value in draws)


def _prediction_rows(
    values: Sequence[Any],
    *,
    column: str = "prediction",
    cohort: str = "region:north",
    model_name: str = "revenue-model",
    model_version: str = "v1",
    extra: Mapping[str, Sequence[Any]] | None = None,
) -> tuple[dict[str, Any], ...]:
    rows: list[dict[str, Any]] = []
    for index, value in enumerate(values):
        row: dict[str, Any] = {
            column: value,
            "model_name": model_name,
            "model_version": model_version,
            "cohort_key": cohort,
            # Deliberately outside prediction_columns: it must never reach the
            # drift frame, and the baseline records that it does not.
            "entity_id": f"entity-{index}",
        }
        if extra:
            for extra_column, extra_values in extra.items():
                row[extra_column] = extra_values[index]
        rows.append(row)
    return tuple(rows)


